// Firmware pin maps from the MCU's net assignments, plus detection of pin changes between revisions.

export interface PinAssignment {
  /** MCU pin name, e.g. PA5 (STM32) or P0.13 (nRF). */
  pin: string;
  net: string;
}

export interface GpioRef {
  controller: string;
  index: number;
}

/** Map a vendor pin name to a Zephyr GPIO controller label and index; null if the name is not a GPIO. */
export function parseGpio(pin: string): GpioRef | null {
  const stm = /^P([A-K])(\d{1,2})$/i.exec(pin);
  if (stm) return { controller: `gpio${stm[1]!.toLowerCase()}`, index: Number(stm[2]) };
  const nrf = /^P(\d)[._](\d{1,2})$/i.exec(pin);
  if (nrf) return { controller: `gpio${nrf[1]}`, index: Number(nrf[2]) };
  return null;
}

/** Net name → C identifier (`/SPI_MOSI` → `SPI_MOSI`, `+3V3` → `P3V3`, `LED-1` → `LED_1`). */
export function netIdentifier(net: string): string {
  let id = net.replace(/^\/+/, '').replace(/^\+/, 'P').replace(/^-/, 'N').replace(/[^A-Za-z0-9]+/g, '_').replace(/^_+|_+$/g, '').toUpperCase();
  if (!id) id = 'NET';
  if (/^\d/.test(id)) id = `N_${id}`;
  return id;
}

const isUnconnected = (net: string) => net === '' || /^unconnected-/i.test(net) || /^no_?connect$/i.test(net);

function usable(pins: PinAssignment[]): (PinAssignment & { id: string })[] {
  const seen = new Map<string, number>();
  return pins
    .filter((p) => !isUnconnected(p.net))
    .sort((a, b) => a.pin.localeCompare(b.pin, undefined, { numeric: true }))
    .map((p) => {
      const base = netIdentifier(p.net);
      const n = seen.get(base) ?? 0;
      seen.set(base, n + 1);
      return { ...p, id: n === 0 ? base : `${base}_${n + 1}` };
    });
}

export function generatePinsHeader(pins: PinAssignment[], guard = 'PINS_H'): string {
  const rows = usable(pins);
  const lines = [`#ifndef ${guard}`, `#define ${guard}`, '', '/* Generated by Jumper from the schematic. Do not edit by hand. */', ''];
  for (const p of rows) {
    const g = parseGpio(p.pin);
    lines.push(g ? `#define PIN_${p.id} ${g.index} /* ${p.pin} (${g.controller}), net ${p.net} */` : `/* ${p.pin}: net ${p.net} (not a GPIO) */`);
  }
  lines.push('', `#endif /* ${guard} */`, '');
  return lines.join('\n');
}

/** Zephyr overlay exposing each GPIO net as a `zephyr,user` property. */
export function generateZephyrOverlay(pins: PinAssignment[]): string {
  const gpios = usable(pins).flatMap((p) => {
    const g = parseGpio(p.pin);
    return g ? [{ ...p, g }] : [];
  });
  const props = gpios.map((p) => `\t\t${p.id.toLowerCase().replace(/_/g, '-')}-gpios = <&${p.g.controller} ${p.g.index} GPIO_ACTIVE_HIGH>; /* ${p.pin}, net ${p.net} */`);
  return ['/* Generated by Jumper from the schematic. */', '#include <zephyr/dt-bindings/gpio/gpio.h>', '', '/ {', '\tzephyr,user {', ...props, '\t};', '};', ''].join('\n');
}

export function generatePinsCsv(pins: PinAssignment[]): string {
  const esc = (s: string) => (/[",\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s);
  return ['pin,net,identifier', ...usable(pins).map((p) => [p.pin, p.net, p.id].map(esc).join(','))].join('\n') + '\n';
}

export interface PinChange {
  pin: string;
  before: string | null;
  after: string | null;
}

export function diffPinMaps(before: PinAssignment[], after: PinAssignment[]): PinChange[] {
  const a = new Map(before.filter((p) => !isUnconnected(p.net)).map((p) => [p.pin, p.net]));
  const b = new Map(after.filter((p) => !isUnconnected(p.net)).map((p) => [p.pin, p.net]));
  const changes: PinChange[] = [];
  for (const pin of new Set([...a.keys(), ...b.keys()])) {
    const x = a.get(pin) ?? null;
    const y = b.get(pin) ?? null;
    if (x !== y) changes.push({ pin, before: x, after: y });
  }
  return changes.sort((p, q) => p.pin.localeCompare(q.pin, undefined, { numeric: true }));
}

/** Pins that two nets claim on the same MCU pin or one net spread over several pins that share a peripheral name. */
export function findPinConflicts(pins: PinAssignment[]): string[] {
  const out: string[] = [];
  const byPin = new Map<string, Set<string>>();
  for (const p of pins) {
    if (isUnconnected(p.net)) continue;
    byPin.set(p.pin, (byPin.get(p.pin) ?? new Set()).add(p.net));
  }
  for (const [pin, nets] of byPin) if (nets.size > 1) out.push(`${pin} is connected to several nets: ${[...nets].join(', ')}`);
  return out;
}
